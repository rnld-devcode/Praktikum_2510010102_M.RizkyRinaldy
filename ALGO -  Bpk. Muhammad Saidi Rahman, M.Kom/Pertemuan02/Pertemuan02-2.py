#Operator Perbandingan (Hasil yang didapat adalah Bolean(T/F))
#==,    Sama dengan
#!=,    Tidak Sama Dengan
#>,     Lebih Besar dari
#<,     Lebih Kecil dari
#>=,    Lebih Besar atau Sama dengan
#<=,    Lebih Kecil atau Sama dengan

print("Materi Pertemuan02 - Contoh 2: Operator Perbandingan")
bil1 = float(input("Masukan bilangan pertama: "))
bil2 = float(input("Masukan bilangan kedua: "))

#Output - Hasil Keluaran Program
print("Hasil Operator == : ", bil1 == bil2)
print("Hasil Operator != : ", bil1 != bil2)
print("Hasil Operator >  : ", bil1 > bil2)
print("Hasil Operator <  : ", bil1 < bil2)
print("Hasil Operator >= : ", bil1 >= bil2)
print("Hasil Operator <= : ", bil1 <= bil2)